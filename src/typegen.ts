import * as AST from "./ast";

// Collects all type names used in the program and generates types.js

export function collectTypes(program: AST.Program): Set<string> {
    const types = new Set<string>();

    function visitTypeExpr(t: AST.TypeExpr | undefined) {
        if (!t) return;
        switch (t.kind) {
            case "SimpleType": types.add(t.name); break;
            case "GenericType": types.add(t.name); t.params.forEach(visitTypeExpr); break;
            case "UnionType": t.types.forEach(visitTypeExpr); break;
            case "NullableType": visitTypeExpr(t.inner); break;
        }
    }

    function visitParam(p: AST.Param) { visitTypeExpr(p.type); }
    function visitStmts(stmts: AST.Stmt[]) { stmts.forEach(visitStmt); }

    function visitStmt(s: AST.Stmt) {
        switch (s.kind) {
            case "FnDecl":
                s.params.forEach(visitParam);
                visitTypeExpr(s.returnType);
                visitStmts(s.body);
                break;
            case "ClassDecl":
                s.body.forEach((m) => {
                    if (m.kind === "Property") visitTypeExpr(m.type);
                    else { m.params.forEach(visitParam); visitTypeExpr(m.returnType); visitStmts(m.body); }
                });
                break;
            case "VarDecl": visitTypeExpr(s.type); break;
            case "If": visitStmts(s.then); s.elifs.forEach((e) => visitStmts(e.body)); if (s.else) visitStmts(s.else); break;
            case "For": visitStmts(s.body); break;
            case "While": visitStmts(s.body); break;
        }
    }

    visitStmts(program.stmts);
    return types;
}

// Built-in type implementations
const BUILTIN_CHECKERS: Record<string, { check: string; coerce?: string }> = {
    String:    { check: `typeof v === 'string'`,    coerce: `String(v)` },
    Number:    { check: `typeof v === 'number' && !isNaN(v)`, coerce: `Number(v)` },
    Boolean:   { check: `typeof v === 'boolean'`,   coerce: `Boolean(v)` },
    Integer:   { check: `Number.isInteger(v)`,       coerce: `Math.trunc(Number(v))` },
    Float:     { check: `typeof v === 'number'`,     coerce: `parseFloat(String(v))` },
    Array:     { check: `Array.isArray(v)` },
    Object:    { check: `typeof v === 'object' && v !== null && !Array.isArray(v)` },
    Function:  { check: `typeof v === 'function'` },
    Date:      { check: `v instanceof Date` },
    RegExp:    { check: `v instanceof RegExp` },
    Symbol:    { check: `typeof v === 'symbol'` },
    BigInt:    { check: `typeof v === 'bigint'` },
    Any:       { check: `true` },
    Unknown:   { check: `true` },
    Never:     { check: `false` },
    Void:      { check: `v === undefined || v === null` },
    Null:      { check: `v === null` },
    Undefined: { check: `v === undefined` },
};

export function generateTypesFile(typeNames: Set<string>): string {
    const lines: string[] = [
        `// types.js — auto-generated by brewlang`,
        `// Do not edit manually. Re-run 'brew compile' to regenerate.`,
        ``,
        `/** @typedef {{ check: (v: unknown) => boolean, assert: (v: unknown, name?: string) => unknown, coerce?: (v: unknown) => unknown }} TypeDef */`,
        ``,
    ];

    const generated: string[] = [];

    for (const name of typeNames) {
        if (name === "void" || name === "never" || name.startsWith("_")) continue;
        const builtin = BUILTIN_CHECKERS[name];
        const checkFn = builtin?.check ?? `v instanceof ${name}`;
        const coerceFn = builtin?.coerce;

        generated.push(`// --- ${name} ---`);
        generated.push(`export const is${name} = (v) => ${checkFn};`);
        generated.push(`export const assert${name} = (v, name = '${name}') => {`);
        generated.push(`  if (!(${checkFn})) throw new TypeError(\`\${name}: expected ${name}, got \${v === null ? 'null' : typeof v} '\${v}'\`);`);
        generated.push(`  return v;`);
        generated.push(`};`);
        if (coerceFn) {
            generated.push(`export const coerce${name} = (v) => ${coerceFn};`);
        }
        generated.push(``);
    }

    lines.push(...generated);

    // Runtime Types registry object
    lines.push(`/** Runtime type registry — use Types.String.check(v) or Types.String.assert(v, 'fieldName') */`);
    lines.push(`export const Types = {`);
    for (const name of typeNames) {
        if (name === "void" || name === "never" || name.startsWith("_")) continue;
        const builtin = BUILTIN_CHECKERS[name];
        const coerceFn = builtin?.coerce;
        lines.push(`  ${name}: { check: is${name}, assert: assert${name}${coerceFn ? `, coerce: coerce${name}` : ""} },`);
    }
    lines.push(`};`);
    lines.push(``);

    // Schema validator helper
    lines.push(`/**`);
    lines.push(` * Validate an object against a shape schema`);
    lines.push(` * @example validate({ name: Types.String, age: Types.Number }, obj)`);
    lines.push(` */`);
    lines.push(`export function validate(schema, obj) {`);
    lines.push(`  const errors = [];`);
    lines.push(`  for (const [key, typeDef] of Object.entries(schema)) {`);
    lines.push(`    try { typeDef.assert(obj[key], key); }`);
    lines.push(`    catch (e) { errors.push(e.message); }`);
    lines.push(`  }`);
    lines.push(`  if (errors.length) throw new TypeError('Validation failed:\\n  ' + errors.join('\\n  '));`);
    lines.push(`  return obj;`);
    lines.push(`}`);
    lines.push(``);

    // Schema-based factory
    lines.push(`/**`);
    lines.push(` * Create a validated constructor for a given schema`);
    lines.push(` * @example const makeUser = createSchema({ name: Types.String, age: Types.Number })`);
    lines.push(` * const user = makeUser({ name: 'Alice', age: 30 })`);
    lines.push(` */`);
    lines.push(`export function createSchema(schema) {`);
    lines.push(`  return (obj) => validate(schema, obj);`);
    lines.push(`}`);

    return lines.join("\n");
}
